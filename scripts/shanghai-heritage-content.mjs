export function classifyHeritage(title) {
  if (/盆景|栽培/.test(title)) return 'garden';
  if (/里弄|营造|木作|修缮/.test(title)) return 'construction';
  if (/小笼|糕|羊肉|丁蹄|菜点|蛋糕|米糕|烹饪|酿造|乳腐|糖果/.test(title)) return 'food';
  if (/旗袍|裁缝|女装|绒绣|刺绣|顾绣|编织|草编|挑花|丝毯|土布|香囊|盘扣|钩针/.test(title)) return 'textile';
  if (/音乐|丝竹|琵琶|二胡|锣鼓|吹打|乐器/.test(title)) return 'music';
  if (/越剧|皮影|说书|说唱|宣卷|戏/.test(title)) return 'performance';
  if (/山歌|田歌|民歌|沪谚|俗语|谚语|故事/.test(title)) return 'oral';
  if (/龙舞|手狮|滚灯|庙会|民俗|婚俗|摇快船|调狮|舞蹈/.test(title)) return 'custom';
  if (/画|漫画|剪纸|篆刻|水印|印泥|纸艺/.test(title)) return 'visual';
  return 'craft';
}

export function buildHeritageContent({ title, district, sourceUrl, admin = false }) {
  const type = classifyHeritage(title);
  const spec = TYPE_SPECS[type];
  const context = DISTRICT_CONTEXT[district.id] || `${district.name}保留了多样的地方文化传统`;
  const focus = ADMIN_FOCUS[title] || `${title}需要结合具体传承场景理解其材料、程式、参与者和当代保护方式。`;
  const sourceStatement = admin
    ? `项目名称与区属来自本批次登记的公开名录来源；${focus}`
    : `该条目作为共建线索保留，名称、区属和项目级细节应由投稿人及管理员结合原始来源复核。${focus}`;
  const summary = `${title}是${district.name}的${spec.category}项目。${sourceStatement}${context}，因此阅读这个项目时，不只要看最终作品或一次表演，也要同时关注它依赖的材料、空间、参与者协作，以及传统在当代社区中的延续方式。`;
  const history = `${context}。本条目的历史沿革不使用无来源的具体年代或传承人结论；审核时应从“形成环境、代表性传承、保护单位、当代实践”四项补入可引用资料。`;
  const features = `${focus}在展示中可从“准备—核心操作或表演—成果—记录”四层观察，并比较它与${district.name}生活环境之间的联系。`;
  const steps = spec.steps.map(([name, description, result, materials, tools, actions]) => ({
    name, description: `${description}${admin ? '' : ' 此流程为资料整理建议，提交审核时请按项目实际情况修订。'}`,
    result, materials, tools, actions, documentary_clips: [],
  }));
  const relations = [
    { type: 'region', title: district.name, summary: `${title}在本批次按${district.name}项目维护，区属需以所列公开来源为准。` },
    { type: 'tradition', title: spec.tradition, summary: `${title}可放在“${spec.tradition}”中比较其地方特征与共通方法。` },
    { type: 'material', title: spec.material, summary: `${spec.material}是理解${title}制作、表演或记录方式的重要线索。` },
  ];
  return {
    type, category: spec.category, summary, history, features, steps,
    graphSummary: `${title}连接${district.name}、${spec.tradition}和${spec.material}。地区节点解释它生长的空间与社区语境，传统节点用于比较同类项目的方法差异，材料节点则揭示技艺或表演如何被具体媒介支撑；进入节点后可沿这三条关系继续探索。`,
    relations,
    keywords: [title, district.name, spec.category, spec.tradition, spec.material],
    sourceUrl,
  };
}

